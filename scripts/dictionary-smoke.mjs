import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { indexSearchEntry, crossReferences } from '../lib/dictionary/search.mjs';

export async function checkDictionary(browser, base) {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const errors = [];
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await context.route('**/*', route => route.request().url().startsWith(base + '/') ? route.continue() : route.abort());
  try {
    await page.goto(base + '/dictionary/');
    await page.locator('.dictionary-results[data-state="ready"]').waitFor();
    const query = page.getByRole('textbox', { name: 'Dictionary search' });
    const cards = page.locator('a[href^="/dictionary/entry/"]');
    const initialWords=await cards.allTextContents();
    assert.doesNotMatch(await page.locator('.dictionary-results').innerText(),/Tag:|Greek:|Etymology:|Crum 1a/);
    assert.ok(await page.getByText('Bohairic',{exact:true}).count()>0,'Dialect badges remain');
    assert.ok(await page.getByText('Imperative',{exact:true}).count()>0,'Parts of speech remain');
    assert.equal(initialWords.length,24,'The first render is a small batch');
    assert.equal(await page.getByText('Dialect labels',{exact:true}).count(),0);
    assert.equal(await page.getByText(/of [\d,]+ entries/).count(),0);
    assert.equal(await page.getByRole('button',{name:'Show 80 more',exact:true}).count(),0);
    assert.equal(await page.workers().length,1,'Dictionary preparation and search run in a background worker');
    const dictionaryWorker=page.workers()[0];
    await page.locator('.dictionary-scroll-sentinel').scrollIntoViewIfNeeded();
    await page.waitForFunction(()=>document.querySelectorAll('.dictionary-entry-card').length>=48);
    assert.deepEqual((await cards.allTextContents()).slice(0,24),initialWords,'Appending entries preserves the existing order');
    await page.locator('.dictionary-scroll-sentinel').scrollIntoViewIfNeeded();
    await page.waitForFunction(()=>document.querySelectorAll('.dictionary-entry-card').length>=72);
    await page.emulateMedia({reducedMotion:'reduce'});
    assert.equal(await page.locator('.dictionary-entry-card').first().evaluate(el=>getComputedStyle(el).animationName),'none');
    await page.emulateMedia({reducedMotion:'no-preference'});
    assert.equal(await page.locator('select, input[type=checkbox]').count(), 0);
    await query.focus();
    assert.equal(await query.evaluate(el => getComputedStyle(el).outlineStyle), 'none');
    const settings = async (update) => {
      await page.getByRole('link', { name: 'Advanced dictionary settings', exact: true }).click();
      await page.getByRole('heading', { name: 'Dictionary settings', exact: true }).waitFor();
      await page.waitForLoadState('networkidle');
      await page.waitForFunction(()=>document.querySelector('[aria-label="Part of speech"]')?.querySelectorAll('option').length>1);
      assert.ok(await page.getByLabel('Part of speech', {exact:true}).locator('option').count() > 1, 'Parts of speech populate from the dictionary');
      assert.equal(await page.getByRole('alert').filter({hasText:'Parts of speech could not be loaded'}).count(), 0);
      await update();
      await page.getByRole('link', { name: 'Done', exact: true }).click();
      await page.locator('.dictionary-results[data-state="ready"]').waitFor();
      assert.ok(page.workers().includes(dictionaryWorker),'Returning from settings reuses the prepared dictionary');
      await page.waitForLoadState('networkidle');
    };
    await settings(() => page.getByLabel('Search in', { exact: true }).selectOption('transliteration'));
    await query.fill('agapi');
    await page.getByText('Transliteration · approximate spelling', { exact: false }).first().waitFor();
    await page.locator('a[href^="/dictionary/entry/"]').filter({ hasText: 'ⲁⲅⲁⲡⲏ' }).first().waitFor();
    await settings(() => page.getByLabel('Search in', { exact: true }).selectOption('english'));
    await query.fill('god love');
    await page.getByText('Definition · whole words', { exact: false }).first().waitFor();
    assert.ok(await cards.count() > 0);
    await query.fill('lvoe');
    await page.getByRole('button', { name: 'love', exact: true }).waitFor();
    assert.equal(await query.inputValue(), 'lvoe', 'Suggestions do not silently rewrite input');
    await page.getByRole('button', { name: 'love', exact: true }).click();
    await page.getByText('English meaning · exact', { exact: true }).first().waitFor();
    assert.equal(await page.getByLabel('Spelling suggestions',{exact:true}).count(),0,'Good matches do not invite unnecessary spelling corrections');
    await settings(() => page.getByLabel('Search in', { exact: true }).selectOption('coptic'));
    await query.fill('ⲁ');
    await settings(() => page.getByLabel('Search without combining marks').uncheck());
    await page.waitForTimeout(250);
    assert.ok(!(await cards.allTextContents()).includes('ⲁ̄'));
    assert.equal(await page.locator('a[href^="crum:"]').count(), 0);
    await page.getByRole('link', { name: 'ⲁ', exact: true }).first().click();
    await page.getByRole('heading', { name: 'ⲁ', exact: true }).waitFor();
    await page.getByText('First letter of the alphabet', { exact: true }).waitFor();
    assert.doesNotMatch(await page.locator('main').innerText(),/Tag:|Greek:|Etymology:|Crum 1a/);
    assert.equal(await page.getByRole('button', { name: 'Bohairic-only', exact: true }).getAttribute('aria-disabled'),'true');
    await page.getByRole('button', { name: 'Bohairic-only', exact: true }).click({force:true});
    await page.getByRole('status').filter({hasText:'This is locked by Settings.'}).waitFor();
    await page.getByRole('main').getByRole('link', { name: 'Dictionary', exact: true }).click();
    await query.waitFor();
    await page.waitForFunction(() => document.querySelector('[aria-label="Dictionary search"]').value === 'ⲁ');
    await settings(async () => {
      assert.equal(await page.getByLabel('Search in', { exact: true }).inputValue(), 'coptic');
      assert.ok(!(await page.getByLabel('Search without combining marks').isChecked()));
    });
    assert.equal(await query.inputValue(), 'ⲁ', 'Settings preserve the current search');
    await page.getByRole('button', { name: 'Clear', exact: true }).click();
    await query.fill('zzzz_no_such_word_zzzz');
    await page.getByRole('status').filter({ hasText: 'No matching entries' }).waitFor();
    assert.equal(await cards.count(), 0);
    const raw = JSON.parse(await readFile('public/bohairic_dictionary.json', 'utf8'));
    const index = raw.map(r => indexSearchEntry({ lemma: r.word, forms: r.bohairic_variants, gloss: r.senses }));
    const reference = index.find(item => crossReferences(item.entry, index).some(target => target !== item.entry.lemma));
    const target = crossReferences(reference.entry, index).find(target => target !== reference.entry.lemma);
    await page.goto(base + '/dictionary/entry/?lemma=' + encodeURIComponent(reference.entry.lemma));
    await page.getByRole('link', { name: 'See ' + target, exact: true }).first().click();
    await page.getByRole('heading', { name: target, exact: true }).waitFor();
    // Missing dictionary resources surface a themed error and can be retried.
    const fail = route => route.fulfill({ status: 404, body: 'Missing' });
    await context.route('**/bohairic_dictionary.json', fail);
    await page.goto(base + '/dictionary/');
    await page.getByRole('alert').filter({ hasText: 'Failed to load dictionary files' }).waitFor();
    await context.unroute('**/bohairic_dictionary.json', fail);
    await page.getByRole('button', { name: 'Retry', exact: true }).click();
    await page.locator('.dictionary-results[data-state="ready"]').waitFor();
    await page.getByRole('alert').filter({ hasText: 'Failed to load dictionary files' }).waitFor({ state: 'hidden' });
    await page.waitForLoadState('networkidle');
    assert.deepEqual(errors, []);
    console.log('PASS: background dictionary search, small batches, infinite scrolling, reduced motion, transliteration, ranked meanings, suggestions, strict marks, entry links, preferences and offline retry.');
  } catch (error) { console.error("Dictionary failure:", (await page.locator("body").innerText()).slice(0, 2400)); throw error; } finally { await context.close(); }
}
